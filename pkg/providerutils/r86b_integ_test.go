// cr-r86b-tools-to-integrator 4: TS response headers are
// Object.fromEntries(response.headers.entries()): repeated lines joined with
// ", " and each byte one character (node fetch reads `X-U: \xc3\xa9z` as
// "Ã©z"). FetchURL is TS fetch's new URL(input).href / TypeError text.
func TestR86bintegExtractHeadersAndFetchURL(t *testing.T) {
	h := ExtractHeaders(http.Header{"X-U": {"\xc3\xa9z"}, "X-A": {"a", "b"}, "X-P": {"plain"}})
	if h["X-U"] != "\u00c3\u00a9z" || h["X-A"] != "a, b" || h["X-P"] != "plain" {
		t.Errorf("ExtractHeaders = %q", h)
	}
	for _, tc := range []struct{ in, want, err string }{
		{"https://h.example/caf\u00c3\u00a9?q=\u00e9", "https://h.example/caf%C3%83%C2%A9?q=%C3%A9", ""},
		{"https://H.example:443/a/../b", "https://h.example/b", ""},
		{"http://[::1", "", "Failed to parse URL from http://[::1"},
	} {
		got, err := FetchURL(tc.in)
		if got != tc.want || (err == nil) != (tc.err == "") || (err != nil && err.Error() != tc.err) {
			t.Errorf("FetchURL(%q) = %q, %v; want %q, %q", tc.in, got, err, tc.want, tc.err)
		}
	}
}

// cr-r86b-tools-to-integrator 2 (medium): the sandbox text helpers follow TS
// Buffer.from(bytes).toString(encoding) / Buffer.from(content, encoding)
// (sandbox-vercel / sandbox-just-bash readTextFile / writeTextFile), not
// WHATWG labels. Every case was printed by Node 24 (testdata, generated by a
// script over 3 byte inputs, 9 texts and 19 encoding names); an encoding of
// null is Go's "" (TS default "utf-8").
func TestR86bintegSandboxTextNodeBufferEncodings(t *testing.T) {
	raw, err := os.ReadFile("testdata/r86b_integ_node_buffer.json")
	if err != nil {
		t.Fatal(err)
	}
	var cases struct {
		Decode []struct {
			Bytes string  `json:"bytes"`
			Enc   *string `json:"enc"`
			OK    *string `json:"ok"`
			Err   string  `json:"err"`
		} `json:"decode"`
		Encode []struct {
			Text string  `json:"text"`
			Enc  *string `json:"enc"`
			OK   *string `json:"ok"`
			Err  string  `json:"err"`
		} `json:"encode"`
	}
	if err := json.Unmarshal(raw, &cases); err != nil {
		t.Fatal(err)
	}
	isUTF16 := map[string]bool{"ucs2": true, "ucs-2": true, "utf16le": true, "utf-16le": true}
	label := func(e *string) string {
		if e == nil {
			return ""
		}
		return *e
	}
	for _, c := range cases.Decode {
		data, _ := hex.DecodeString(c.Bytes)
		got, err := DecodeSandboxText(data, label(c.Enc))
		switch {
		case c.OK == nil:
			if err == nil || err.Error() != c.Err {
				t.Errorf("decode %s as %q: %q, %v; want error %q", c.Bytes, label(c.Enc), got, err, c.Err)
			}
		case isUTF16[strings.ToLower(label(c.Enc))]:
			// UTF-16: a JS string can hold a lone surrogate, a Go string
			// cannot (it reads as U+FFFD); compare the code points Go can hold.
			want := strings.ToValidUTF8(*c.OK, "\ufffd")
			if err != nil || got != want {
				t.Errorf("decode %s as %q = %q, %v; want %q", c.Bytes, label(c.Enc), got, err, want)
			}
		default:
			if err != nil || got != *c.OK {
				t.Errorf("decode %s as %q = %q, %v; want %q", c.Bytes, label(c.Enc), got, err, *c.OK)
			}
		}
	}
	for _, c := range cases.Encode {
		got, err := EncodeSandboxText(c.Text, label(c.Enc))
		if c.OK == nil {
			if err == nil || err.Error() != c.Err {
				t.Errorf("encode %q as %q: %x, %v; want error %q", c.Text, label(c.Enc), got, err, c.Err)
			}
			continue
		}
		if err != nil || hex.EncodeToString(got) != *c.OK {
			t.Errorf("encode %q as %q = %x, %v; want %s", c.Text, label(c.Enc), got, err, *c.OK)
		}
	}
}
