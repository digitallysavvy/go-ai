func TestIdentSuffix(t *testing.T) {
	tests := map[string]string{
		"openai/gpt-5.5":                   "OpenaiGpt55",
		"alibaba/qwen3-235b-a22b-thinking": "AlibabaQwen3235bA22bThinking",
		"cohere/embed-v4.0":                "CohereEmbedV40",
		"zai/glm-5v-turbo":                 "ZaiGlm5vTurbo",
		"spacexai/grok-build-0.1":          "SpacexaiGrokBuild01",
		"typesafe-ai/jev":                  "TypesafeAiJev",
		"perplexity/pplx-embed-v1-0.6b":    "PerplexityPplxEmbedV106b",
	}
	for id, want := range tests {
		if got := identSuffix(id); got != want {
			t.Errorf("identSuffix(%q) = %q, want %q", id, got, want)
		}
	}
}

func TestParseUnion(t *testing.T) {
	multi := "export type GatewaySpeechModelId =\n  | 'openai/tts-1'\n  | 'openai/tts-1-hd'\n  | (string & {});\n"
	got, err := parseUnion(multi, "GatewaySpeechModelId")
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{"openai/tts-1", "openai/tts-1-hd"}; !reflect.DeepEqual(got, want) {
		t.Fatalf("multi-line union = %v, want %v", got, want)
	}

	single := "export type GatewayEvaluationModelId = 'typesafe-ai/jev' | (string & {});\n"
	got, err = parseUnion(single, "GatewayEvaluationModelId")
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{"typesafe-ai/jev"}; !reflect.DeepEqual(got, want) {
		t.Fatalf("single-line union = %v, want %v", got, want)
	}

	open := "export type GatewaySpeechModelId = string & {};\n"
	got, err = parseUnion(open, "GatewaySpeechModelId")
	if err != nil || len(got) != 0 {
		t.Fatalf("open union = %v, %v; want empty", got, err)
	}

	if _, err := parseUnion(multi, "Missing"); err == nil {
		t.Fatal("expected error for missing type")
	}
	if _, err := parseUnion("export type X = 'a/b' | 'a/b';", "X"); err == nil {
		t.Fatal("expected error for duplicate ID")
	}
}

func TestRenderRejectsIdentifierCollisions(t *testing.T) {
	_, err := render(map[string][]string{"language": {"a/b-c", "a/b.c"}})
	if err == nil || !strings.Contains(err.Error(), "collides") {
		t.Fatalf("render error = %v, want collision error", err)
	}
}

func TestRenderEmitsAllKinds(t *testing.T) {
	src, err := render(map[string][]string{
		"language":   {"openai/gpt-5.5"},
		"evaluation": {"typesafe-ai/jev"},
	})
	if err != nil {
		t.Fatal(err)
	}
	out := string(src)
	for _, want := range []string{
		"// Code generated by internal/gen",
		"DO NOT EDIT.",
		`GatewayLanguageModelOpenaiGpt55 GatewayLanguageModelID = "openai/gpt-5.5"`,
		`GatewayEvaluationModelTypesafeAiJev GatewayEvaluationModelID = "typesafe-ai/jev"`,
		"var GatewaySpeechModelIDs = []GatewaySpeechModelID{}",
		"var GatewayRealtimeModelIDs = []GatewayRealtimeModelID{}",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("rendered output missing %q", want)
		}
	}
}

func TestResolveSrcDir(t *testing.T) {
	root := t.TempDir()
	src := filepath.Join(root, "packages", "gateway", "src")
	if err := os.MkdirAll(src, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(src, "gateway-language-model-settings.ts"), nil, 0o644); err != nil {
		t.Fatal(err)
	}
	for _, dir := range []string{root, src} {
		got, err := resolveSrcDir(dir)
		if err != nil || got != src {
			t.Errorf("resolveSrcDir(%q) = %q, %v; want %q", dir, got, err, src)
		}
	}
	if _, err := resolveSrcDir(t.TempDir()); err == nil {
		t.Error("expected error for directory without settings files")
	}
}
